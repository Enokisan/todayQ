// 日付ベースで問いを選択する関数
export function getTodaysQuestion() {
  const today = new Date();
  const dayOfYear = Math.floor((today - new Date(today.getFullYear(), 0, 0)) / 1000 / 60 / 60 / 24);
  const index = dayOfYear % questions.length;
  return questions[index];
}

